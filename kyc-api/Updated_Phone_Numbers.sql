  WHEN 'TEMP-1'  THEN '0821110001'
  WHEN 'TEMP-2'  THEN '0821110002'
  WHEN 'TEMP-6'  THEN '0821110006'
  WHEN 'TEMP-7'  THEN '0821110007'
  WHEN 'TEMP-8'  THEN '0821110008'
  WHEN 'TEMP-13' THEN '0821110013'
  WHEN 'TEMP-14' THEN '0821110014'
  WHEN 'TEMP-15' THEN '0821110015'
  WHEN 'TEMP-17' THEN '0821110017'
  WHEN 'TEMP-18' THEN '0821110018'
  WHEN 'TEMP-19' THEN '0821110019'
  WHEN 'TEMP-20' THEN '0821110020'
