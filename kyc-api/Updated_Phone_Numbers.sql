END
WHERE id_number IN (
  'TEMP-1','TEMP-2','TEMP-6','TEMP-7','TEMP-8','TEMP-13',
  'TEMP-14','TEMP-15','TEMP-17','TEMP-18','TEMP-19','TEMP-20'
